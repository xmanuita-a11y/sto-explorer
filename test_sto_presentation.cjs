const assert=require('node:assert/strict'),fs=require('node:fs');
globalThis.StoReader=require('./sto-reader-core.js');
const p=require('./sto-reader-presentation.js');
const pressure=p.describe('lfTireColdPressPa'),spring=p.describe('rrSpringRateNpm'),length=p.describe('lfPerchOffsetm');
assert.equal(pressure.label,'Pressione a freddo · anteriore sinistra');
assert.equal(pressure.group,'Pneumatici');
assert.equal(p.format('225000',pressure,'metric').primary,'2,25 bar');
assert.equal(p.format('225000',pressure,'imperial').primary,'32,63 psi');
assert.equal(p.format('100000',pressure,'imperial').primary,'14,5 psi');
assert.equal(p.format('100000',spring,'metric').primary,'100 N/mm');
assert.equal(p.format('175126.835246477',spring,'imperial').primary,'1000 lbf/in');
assert.equal(p.format('0.0254',length,'imperial').primary,'1 in');
assert.equal(p.format('-0.001',length,'metric').primary,'-1 mm');
assert.equal(p.format('0.45359237',p.describe('fuelFillToKg'),'imperial').primary,'1 lb');
assert.equal(p.format('123.456789',p.describe('fuelFillToKg'),'metric').primary,'123,457 kg');
assert.equal(p.format('1.000000',p.describe('driverWeight'),'metric').primary,'1');
assert.equal(p.describe('driverWeight').kind,'raw');
assert.equal(p.describe('lfToeIn').kind,'raw');
assert.equal(p.describe('rWingAngle').kind,'raw');
assert.equal(p.format('3.000000',p.describe('fArbArmIndex')).primary,'3');
assert(p.format('3.000000',p.describe('fArbArmIndex')).secondary.includes('Codice interno'));
assert.equal(p.format(undefined,length).primary,'—');
assert.equal(p.subtract('9007199254740993','9007199254740992'),'-1');
assert.equal(p.subtract('1.000000','1.000001'),'0.000001');
assert.equal(p.subtract('-2.5','-1.25'),'1.25');
assert.equal(p.delta('1.000000','1.000001',pressure,'metric').primary,'≠ sotto la precisione mostrata');
assert.equal(p.delta('100000','200000',pressure,'metric').primary,'+1 bar');
assert.equal(p.delta('200000','100000',pressure,'metric').primary,'-1 bar');
assert.equal(p.format('1.000000',pressure,'raw').primary,'1');
const names=require('./sto-field-names.json');
const coverage={fields:names.length,curated:0,partial:0,convertible:0,groups:{},units_from_field_names:true,garage_equivalence_verified:false};
for(const name of names){
  const d=p.describe(name);assert(d.label);assert(p.groups.includes(d.group));
  coverage[d.quality.startsWith('Nome tecnico')?'partial':'curated']++;
  if(d.kind!=='raw')coverage.convertible++;
  coverage.groups[d.group]=(coverage.groups[d.group]||0)+1;
  for(const units of ['metric','imperial','raw']) assert(p.format('0.000000',d,units).primary);
}
fs.writeFileSync('sto-presentation-coverage.json',JSON.stringify(coverage,null,2));
console.log('PASS: labels, positions, conversions, exact deltas, unverified-field fallback; coverage:',coverage);
